// Helper functions for data management
export const getCourseById = (courseId) => {
return coursesData.find((course) => course.id === parseInt(courseId))
}

export const getQuestionsForCourseVolume = (courseId, volumeId) => {
  return questionsData[courseId]?.[volumeId] || []
}

export const updateCourseProgress = (courseId, volumeId, progress) => {
  const key = `course_progress_${courseId}_${volumeId || "main"}`
  localStorage.setItem(key, JSON.stringify(progress))
}

export const getCourseProgress = (courseId, volumeId) => {
  const key = `course_progress_${courseId}_${volumeId || "main"}`
  const saved = localStorage.getItem(key)
  return saved ? JSON.parse(saved) : null
}

